//! Canonical skills embedded in the binary and their agent-specific formats.
//!
//! The canonical source (`skills/<name>.md` in the repository) is Markdown with
//! a YAML frontmatter holding `name`, `title` and `description`. Agents get one
//! of two renderings:
//!
//! * [`SkillLayout::Folder`] – `<dir>/<name>/SKILL.md` with a frontmatter that
//!   only has `name` and `description` (Claude Code, Codex, Antigravity);
//! * [`SkillLayout::Flat`] – `<dir>/<name>.md` without frontmatter, starting
//!   with `# <Title>` (SiliconFlower reads plain `.md` files).
//!
//! Both renderings end with a [`MANAGED_MARKER`] line. Only files carrying the
//! marker are ever overwritten or deleted by anvil; a user-authored skill with
//! the same name is left alone (and deleting the marker line "adopts" a file).

use std::sync::OnceLock;

use serde::Serialize;

use crate::error::{AgentError, Result};

/// Prefix of the last line of every skill file written by anvil.
pub const MANAGED_MARKER: &str = "<!-- anvil-managed-skill:";

/// `(file name, contents)` of the canonical skills, in display order.
const SOURCES: &[(&str, &str)] = &[
    (
        "anvil-toolkit",
        include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../skills/anvil-toolkit.md")),
    ),
    (
        "rust-systems",
        include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../skills/rust-systems.md")),
    ),
    (
        "c-modern",
        include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../skills/c-modern.md")),
    ),
    (
        "cpp-modern",
        include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../skills/cpp-modern.md")),
    ),
    (
        "cmake-ninja-debug",
        include_str!(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../../skills/cmake-ninja-debug.md"
        )),
    ),
];

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "kebab-case")]
pub enum SkillLayout {
    /// `<dir>/<name>/SKILL.md` with YAML frontmatter.
    Folder,
    /// `<dir>/<name>.md`, plain Markdown starting with `# <Title>`.
    Flat,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Skill {
    pub name: String,
    pub title: String,
    pub description: String,
    /// Markdown body after the frontmatter (no leading/trailing blank lines).
    #[serde(skip)]
    pub body: String,
}

impl Skill {
    /// Parse a canonical skill file (`---` YAML frontmatter + Markdown body).
    pub fn parse(source: &str) -> Result<Self> {
        let invalid = |message: &str| AgentError::InvalidSkill {
            name: source.lines().take(3).collect::<Vec<_>>().join(" "),
            message: message.to_string(),
        };
        let text = source.strip_prefix('\u{feff}').unwrap_or(source).replace("\r\n", "\n");
        let rest = text
            .strip_prefix("---\n")
            .ok_or_else(|| invalid("missing YAML frontmatter"))?;
        let end = rest
            .find("\n---\n")
            .ok_or_else(|| invalid("unterminated YAML frontmatter"))?;
        let (front, body) = (&rest[..end], &rest[end + 5..]);

        let (mut name, mut title, mut description) = (None, None, None);
        for line in front.lines().filter(|l| !l.trim().is_empty()) {
            let (key, value) = line.split_once(':').ok_or_else(|| invalid("bad frontmatter line"))?;
            let value = unquote_yaml(value.trim());
            match key.trim() {
                "name" => name = Some(value),
                "title" => title = Some(value),
                "description" => description = Some(value),
                _ => {}
            }
        }
        let name = name.ok_or_else(|| invalid("missing `name`"))?;
        if !is_valid_skill_name(&name) {
            return Err(invalid("`name` must be lowercase ASCII letters, digits and '-'"));
        }
        Ok(Skill {
            title: title.unwrap_or_else(|| name.clone()),
            description: description.ok_or_else(|| invalid("missing `description`"))?,
            body: body.trim_matches('\n').to_string(),
            name,
        })
    }

    fn marker_line(&self) -> String {
        format!(
            "{MANAGED_MARKER} {} | anvil {} | regenerated by `anvil skills sync`; delete this line to keep local edits -->",
            self.name,
            anvil_core::ANVIL_VERSION
        )
    }

    /// Canonical form: frontmatter with `name`, `title`, `description` + body.
    pub fn canonical(&self) -> String {
        format!(
            "---\nname: {}\ntitle: {}\ndescription: {}\n---\n\n{}\n",
            self.name,
            yaml_quote(&self.title),
            yaml_quote(&self.description),
            self.body
        )
    }

    /// `SKILL.md` for folder-based agents.
    pub fn render_folder(&self) -> String {
        format!(
            "---\nname: {}\ndescription: {}\n---\n\n# {}\n\n{}\n\n{}\n",
            self.name,
            yaml_quote(&self.description),
            self.title,
            self.body,
            self.marker_line()
        )
    }

    /// Plain Markdown for flat agents (no frontmatter, first line `# <Title>`).
    pub fn render_flat(&self) -> String {
        format!(
            "# {}\n\n> {}\n\n{}\n\n{}\n",
            self.title,
            self.description,
            self.body,
            self.marker_line()
        )
    }

    pub fn render(&self, layout: SkillLayout) -> String {
        match layout {
            SkillLayout::Folder => self.render_folder(),
            SkillLayout::Flat => self.render_flat(),
        }
    }
}

/// `true` if `content` was written by anvil (carries the managed marker).
pub fn is_managed(content: &str) -> bool {
    content.lines().any(|l| l.trim_start().starts_with(MANAGED_MARKER))
}

/// Skill names are used as file/folder names: keep them strictly portable.
pub fn is_valid_skill_name(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 64
        && !name.starts_with('-')
        && name
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-')
}

/// All embedded skills (parsed once).
pub fn embedded() -> &'static [Skill] {
    static SKILLS: OnceLock<Vec<Skill>> = OnceLock::new();
    SKILLS.get_or_init(|| {
        SOURCES
            .iter()
            .map(|(file, src)| {
                let skill = Skill::parse(src).unwrap_or_else(|e| panic!("embedded skill {file}.md: {e}"));
                assert_eq!(&skill.name, file, "skill name must match its file name");
                skill
            })
            .collect()
    })
}

pub fn embedded_skill(name: &str) -> Option<&'static Skill> {
    embedded().iter().find(|s| s.name == name)
}

/// Names of every skill managed by anvil.
pub fn managed_names() -> Vec<&'static str> {
    embedded().iter().map(|s| s.name.as_str()).collect()
}

fn yaml_quote(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', r"\\").replace('"', "\\\""))
}

fn unquote_yaml(s: &str) -> String {
    if s.len() >= 2 && s.starts_with('"') && s.ends_with('"') {
        let inner = &s[1..s.len() - 1];
        let mut out = String::with_capacity(inner.len());
        let mut chars = inner.chars();
        while let Some(c) = chars.next() {
            if c == '\\' {
                match chars.next() {
                    Some('n') => out.push('\n'),
                    Some('t') => out.push('\t'),
                    Some(other) => out.push(other),
                    None => out.push('\\'),
                }
            } else {
                out.push(c);
            }
        }
        out
    } else if s.len() >= 2 && s.starts_with('\'') && s.ends_with('\'') {
        s[1..s.len() - 1].replace("''", "'")
    } else {
        s.to_string()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn all_embedded_skills_parse() {
        let names = managed_names();
        assert_eq!(
            names,
            vec![
                "anvil-toolkit",
                "rust-systems",
                "c-modern",
                "cpp-modern",
                "cmake-ninja-debug"
            ]
        );
        for s in embedded() {
            assert!(!s.title.is_empty() && !s.description.is_empty(), "{s:?}");
            assert!(s.body.len() > 500, "{} is suspiciously short", s.name);
            assert!(!s.body.starts_with("# "), "{}: title comes from frontmatter", s.name);
            assert!(!s.body.contains(MANAGED_MARKER));
            // Canonical rendering round-trips.
            assert_eq!(&Skill::parse(&s.canonical()).unwrap(), s);
        }
    }

    #[test]
    fn folder_format_keeps_name_and_description_frontmatter() {
        let s = embedded_skill("rust-systems").unwrap();
        let text = s.render_folder();
        assert!(text.starts_with("---\nname: rust-systems\ndescription: \""), "{text}");
        let reparsed = Skill::parse(&text).unwrap();
        assert_eq!(reparsed.name, s.name);
        assert_eq!(reparsed.description, s.description);
        assert!(!text.contains("\ntitle:"), "agents only expect name + description");
        assert!(text.contains(&format!("\n# {}\n", s.title)));
        assert!(is_managed(&text));
    }

    #[test]
    fn flat_format_has_no_frontmatter() {
        let s = embedded_skill("c-modern").unwrap();
        let text = s.render_flat();
        assert!(text.starts_with(&format!("# {}\n\n", s.title)), "{text}");
        assert!(!text.starts_with("---"));
        assert!(!text.contains("\nname: c-modern"));
        assert!(text.contains(&s.body));
        assert!(is_managed(&text));
        assert!(!is_managed(&s.canonical()));
    }

    #[test]
    fn frontmatter_parsing_edge_cases() {
        let s = Skill::parse("---\r\nname: x-1\r\ndescription: \"a: \\\"b\\\"\"\r\n---\r\n\r\nbody\r\n").unwrap();
        assert_eq!(s.description, "a: \"b\"");
        assert_eq!(s.title, "x-1");
        assert_eq!(s.body, "body");
        assert!(Skill::parse("no frontmatter").is_err());
        assert!(Skill::parse("---\nname: Bad Name\ndescription: d\n---\n").is_err());
        assert!(Skill::parse("---\nname: ok\n---\n").is_err(), "description required");
        assert!(!is_valid_skill_name("../x"));
        assert!(!is_valid_skill_name(""));
    }
}
